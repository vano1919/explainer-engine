"""J1 PR review preparation: the reviewer gets the diff, the card and the invariants, never the PR description; keys are redacted."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

from explainer_engine.llm import claude_api as ca
from explainer_engine.review import pr_review


def git(repo: Path, *a: str) -> str:
    return subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *a], cwd=repo, capture_output=True, text=True, check=True).stdout


def make_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    git(repo, "init", "-q", "-b", "main")
    (repo / "CLAUDE.md").write_text("INVARIANT: no public upload", encoding="utf-8")
    (repo / "a.py").write_text("x = 1\n", encoding="utf-8")
    git(repo, "add", "-A")
    git(repo, "commit", "-qm", "base")
    git(repo, "update-ref", "refs/remotes/origin/main", "HEAD")
    git(repo, "checkout", "-qb", "feature")
    (repo / "a.py").write_text("x = 2\nkey = 'sk-ant-api03-abcdefghijkl'\n", encoding="utf-8")
    git(repo, "commit", "-qam", "change")
    return repo


def test_prepare_builds_a_job_the_client_accepts(tmp_path, monkeypatch):
    repo = make_repo(tmp_path)
    card = tmp_path / "card.md"
    card.write_text("Card: change x to 2", encoding="utf-8")
    out = tmp_path / "out"
    job = pr_review.prepare(repo, 7, "feature", out, card=card)
    sha = git(repo, "rev-parse", "feature").strip()
    spec = json.loads(job.read_text(encoding="utf-8"))
    assert spec["job"] == "J1" and spec["task_class"] == "critical-review" and spec["requests"][0]["cache_salt"] == sha
    user = (out / "user.md").read_text(encoding="utf-8")
    assert sha in user and "Card: change x to 2" in user and "+x = 2" in user
    assert "sk-ant" not in user and "[REDACTED-SECRET-LIKE]" in user
    assert "INVARIANT: no public upload" in (out / "claude_md.md").read_text(encoding="utf-8")
    assert (out / "checkout" / "a.py").read_text(encoding="utf-8").startswith("x = 2")
    reqs = ca.load_job(job)       # passes the secret filter and carries the tool root
    assert reqs[0].tools_root == str((out / "checkout").resolve()) and len(reqs[0].system) == 2


def test_reviewer_prompt_asks_for_verdict_first_and_has_no_author_context():
    assert pr_review.REVIEWER.index("VERDICT") < pr_review.REVIEWER.index("HEAD SHA READ")
    assert "do not see the author's reasoning" in pr_review.REVIEWER


def test_render_adds_model_cost_and_footer(tmp_path):
    (tmp_path / "out").mkdir()
    (tmp_path / "out" / "pr7.md").write_text("VERDICT: APPROVE - ok", encoding="utf-8")
    (tmp_path / "out" / "summary.json").write_text(json.dumps({"pr7": {"model": "claude-opus-5-5", "usd": 0.31},
                                                               "_ledger_total_usd": 0.31}), encoding="utf-8")
    text = pr_review.render(7, tmp_path)
    assert "VERDICT: APPROVE" in text and "claude-opus-5-5" in text and "$0.31" in text and text.rstrip().endswith("_Generated by [Claude Code](https://claude.ai/code)_")
