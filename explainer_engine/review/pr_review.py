"""J1, the PR cross-review (docs/LLM_API.md): an independent reviewer on the Claude API, so reviews do not burn session limits.

``prepare`` builds a job for ``explainer_engine.llm.claude_api``: the diff against the merge base, the phase card, the invariants of
CLAUDE.md at the base, and a read-only checkout of the PR head for the repo tools. The reviewer gets NO PR description and no author
thread (it reasons from facts only). ``render`` turns the answer into the text the phase thread posts as the GitHub review.

    python -m explainer_engine.review.pr_review prepare --pr 30 --head origin/claude/x --card card.md --out DIR
    python -m explainer_engine.llm.claude_api run DIR/job.json --out DIR/out
    python -m explainer_engine.review.pr_review render --pr 30 --out DIR
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from explainer_engine.core.store import write_json_atomic, write_text_atomic
from explainer_engine.llm.claude_api import redact

ROOT = Path(__file__).resolve().parents[2]
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"

REVIEWER = """You are an independent code reviewer for the explainer-engine repository. You see a diff, the phase card it implements and the
repository's invariants. You do not see the author's reasoning, the PR description or any discussion, and you must not guess them.

Method: read the diff; open the changed files and their tests with the tools (list_dir, read_file, grep; read-only) whenever the diff
alone cannot settle a claim; check every invariant of CLAUDE.md that the diff touches (money caps, no public upload, no secrets,
schema contracts, tests not weakened, one home per ID); check that each test would fail if the code were wrong.

Answer format, nothing before the first line:
1. `VERDICT: APPROVE`, `VERDICT: CHANGES REQUESTED` or `VERDICT: COMMENT`, then one sentence of why.
2. `HEAD SHA READ: <sha>` as given in the task.
3. Findings, most severe first, each `path:line - severity (blocker | major | minor) - what is wrong - concrete failing input or state`.
   Only findings you verified in the code; a doubt you could not verify goes under `NOT VERIFIED`.
4. `NOT VERIFIED`: what you could not check (tests not run, files not opened). You cannot run code.
5. `CARD COVERAGE`: each requirement of the phase card as done, partly done or missing, with the file that shows it.
No praise, no summary of the diff, no code rewrites. Be direct."""


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True, check=True).stdout


def prepare(repo: Path, pr: int, head: str, out: Path, *, card: Path | None = None, base: str = "origin/main",
            effort: str = "high", max_turns: int = 24) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    sha = _git(repo, "rev-parse", head).strip()
    merge_base = _git(repo, "merge-base", base, sha).strip()
    diff, hidden = redact(_git(repo, "diff", "--no-color", f"{merge_base}", sha))
    names = _git(repo, "diff", "--stat", merge_base, sha)
    invariants = redact(_git(repo, "show", f"{merge_base}:CLAUDE.md"))[0]
    card_text = redact(card.read_text(encoding="utf-8"))[0] if card else "(no phase card was given; review the diff on its own terms)"
    checkout = out / "checkout"
    if checkout.exists():
        _git(repo, "worktree", "remove", "--force", str(checkout))
    _git(repo, "worktree", "add", "--detach", str(checkout), sha)
    write_text_atomic(out / "reviewer.md", REVIEWER)
    write_text_atomic(out / "claude_md.md", "Invariants and conventions of the repository (CLAUDE.md at the merge base):\n\n" + invariants)
    note = f"\n({hidden} secret-like string(s) in the diff were replaced by [REDACTED-SECRET-LIKE])\n" if hidden else ""
    write_text_atomic(out / "user.md", f"Task: review pull request #{pr}. HEAD SHA READ: {sha}. Merge base: {merge_base}.\n\n"
                      f"## Phase card\n\n{card_text}\n\n## Files changed\n\n{names}\n## Diff\n{note}\n{diff}\n")
    job = {"job": "J1", "task_class": "critical-review", "effort": effort, "max_tokens": 16000, "max_turns": max_turns,
           "system_files": ["reviewer.md", "claude_md.md"], "tools_root": "checkout",
           "requests": [{"id": f"pr{pr}", "user_file": "user.md", "cache_salt": sha}]}
    write_json_atomic(out / "job.json", job)
    return out / "job.json"


def render(pr: int, out: Path) -> str:
    """The review text to post: the model's answer, who wrote it and what it cost (from the run summary), the footer."""
    body = (out / "out" / f"pr{pr}.md").read_text(encoding="utf-8").strip()
    summary = json.loads((out / "out" / "summary.json").read_text(encoding="utf-8"))
    row = summary.get(f"pr{pr}", {})
    head = (f"_Independent review on the Claude API (model {row.get('model', '?')}), from the diff, the phase card and CLAUDE.md only; "
            f"cost ${row.get('usd', 0):.2f}, API ledger total ${summary.get('_ledger_total_usd', 0):.2f}._\n\n")
    return head + body + FOOTER


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="pr_review")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("prepare")
    p.add_argument("--pr", type=int, required=True)
    p.add_argument("--head", required=True, help="the PR head ref or sha, fetched already (git fetch origin <branch>)")
    p.add_argument("--base", default="origin/main")
    p.add_argument("--card", type=Path)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--effort", default="high")
    r = sub.add_parser("render")
    r.add_argument("--pr", type=int, required=True)
    r.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    if a.cmd == "prepare":
        print(prepare(ROOT, a.pr, a.head, a.out, card=a.card, base=a.base, effort=a.effort))
    else:
        print(render(a.pr, a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
